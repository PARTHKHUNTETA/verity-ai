import { LlmError, type LlmClient } from "./types.js";

const FAKE_ANSWER = `## Summary

This answer comes from VerityAI's **fake** LLM provider (\`LLM_PROVIDER=fake\`). It lets you test the
whole pipeline — queue, worker, live streaming, cost tracking — without an API key.

## What a real answer will include

- A direct answer to your question
- Key points, with uncertainty stated honestly
- From Phase 5 on: citations to the exact passages that support each claim

## Next step

Set \`LLM_PROVIDER=openai\` and \`OPENAI_API_KEY\` in \`verity-ai-backend/.env\`, then restart the worker.`;

/**
 * If the input contains numbered passages ("[1] \"Title\"\n<text>"), answer by quoting the
 * first sentence of each and citing it, like a (very literal) grounded model would.
 * Otherwise return the canned explanation.
 */
function defaultAnswer(input: string): string {
  // Passage header line, then the passage text: skip Markdown heading lines inside it.
  const passages = [
    ...input.matchAll(/^\[(\d+)\] "([^"\n]*)"[^\n]*\n(?:#[^\n]*\n+)*([^\n#][^\n]*)/gm),
  ].slice(0, 4);
  if (passages.length === 0) return `> ${input.split("\n")[1] ?? input}\n\n${FAKE_ANSWER}`;
  const points = passages.map(([, n, title, text]) => {
    const sentence = text!.match(/^.{20,240}?[.!?](?=\s|$)/)?.[0] ?? text!.slice(0, 200);
    return `- From *${title}*: ${sentence.replace(/[.!?]$/, "")} [${n}].`;
  });
  return [
    "## Summary",
    "",
    `Your sources contain ${passages.length} relevant passage(s) for this question. This answer was generated by the fake LLM provider, which simply quotes the first sentence of each passage [1].`,
    "",
    "## Key points",
    "",
    ...points,
    "",
    "## Limitations",
    "",
    "The fake provider doesn't reason about the passages. Set LLM_PROVIDER=openai for real answers.",
  ].join("\n");
}

type FakeOptions = {
  /** Text to stream (defaults to a canned answer that echoes the question). */
  answer?: (input: string) => string;
  /** Delay between chunks in ms (0 in tests). */
  delayMs?: number;
  /** Throw this error after streaming `failAfterChunks` chunks. */
  failWith?: Error;
  failAfterChunks?: number;
};

/** Deterministic stand-in for a real model: streams text word by word. */
export function createFakeLlmClient(options: FakeOptions = {}): LlmClient {
  const { delayMs = 25, failWith, failAfterChunks = 0 } = options;
  const answerFor = options.answer ?? defaultAnswer;

  return {
    provider: "fake",

    async streamText({ input, onDelta, signal }) {
      const text = answerFor(input);
      const chunks = text.match(/\S+\s*/g) ?? [];
      let streamed = "";
      for (const [i, chunk] of chunks.entries()) {
        if (failWith && i === failAfterChunks) throw failWith;
        if (signal?.aborted) throw new LlmError("Request was aborted", "ABORTED", false);
        if (delayMs > 0) await sleep(delayMs, signal);
        streamed += chunk;
        onDelta(chunk);
      }
      return {
        text: streamed,
        model: "fake-model",
        usage: {
          inputTokens: Math.ceil(input.length / 4),
          outputTokens: chunks.length,
          cachedInputTokens: 0,
        },
      };
    },

    async embed(texts) {
      return {
        embeddings: texts.map(hashEmbedding),
        usage: {
          inputTokens: Math.ceil(texts.join(" ").length / 4),
          outputTokens: 0,
          cachedInputTokens: 0,
        },
      };
    },
  };
}

/**
 * "Feature hashing": each word adds 1 to a bucket chosen by its hash, then the vector is
 * normalized. Texts that share words get similar vectors, so vector search behaves sensibly
 * (lexically, not semantically) without calling a real embedding model.
 */
function hashEmbedding(text: string): number[] {
  const vector = new Array<number>(1536).fill(0);
  for (const word of text.toLowerCase().match(/[a-z0-9]{3,}/g) ?? []) {
    let h = 2166136261;
    for (let i = 0; i < word.length; i++) h = Math.imul(h ^ word.charCodeAt(i), 16777619);
    vector[(h >>> 0) % 1536]! += 1;
  }
  const norm = Math.hypot(...vector) || 1;
  // A zero vector has no direction (cosine distance is undefined), so nudge empty texts.
  return norm === 1 && vector.every((v) => v === 0)
    ? vector.map((_, i) => (i === 0 ? 1 : 0))
    : vector.map((v) => v / norm);
}

function sleep(ms: number, signal?: AbortSignal) {
  return new Promise<void>((resolve) => {
    const timer = setTimeout(resolve, ms);
    signal?.addEventListener("abort", () => {
      clearTimeout(timer);
      resolve();
    });
  });
}
