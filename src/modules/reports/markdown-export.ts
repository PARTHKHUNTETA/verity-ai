import { buildReferences, type CitationInput } from "./bibliography.js";

/**
 * The exported report: the report itself, then the evidence behind every citation, the
 * bibliography, and how the report was produced and checked. Everything a reader needs to
 * verify it without opening VerityAI.
 */

export type ExportInput = {
  question: string;
  instructions: string | null;
  contentMd: string;
  version: number;
  status: string;
  model: string;
  pipelineVersion: string;
  completedAt: Date | null;
  citations: CitationInput[];
  scorecard: {
    claimSupportRate: number | null;
    citationAccuracy: number | null;
    citationValidity: number | null;
    sourceReliability: number | null;
    coverage: number | null;
    taskCompletion: number | null;
    policyCompliant: boolean;
    passed: boolean;
  } | null;
};

const pct = (v: number | null) => (v === null ? "not measured" : `${Math.round(v * 100)}%`);

/** Quotes go inside "…" on one line: collapse whitespace and escape Markdown-active characters. */
const inlineQuote = (text: string) =>
  text
    .replace(/\s+/g, " ")
    .trim()
    .replace(/([*_`[\]])/g, "\\$1");

export function renderMarkdownExport(input: ExportInput): string {
  const { notes, references } = buildReferences(input.contentMd, input.citations);
  const parts = [input.contentMd.trim()];

  if (notes.length) {
    parts.push(
      "## Evidence",
      notes
        .map(
          (n) =>
            `${n.number}. "${inlineQuote(n.quote)}" (source ${n.referenceIndex}${n.pages ? `, ${n.pages}` : ""})`,
        )
        .join("\n"),
    );
    parts.push(
      "## References",
      references
        .map((r) => `${r.index}. ${r.text} Cited as ${r.citedAs.map((n) => `[${n}]`).join(" ")}.`)
        .join("\n"),
    );
  }

  const about = [
    `- Question: ${input.question.replace(/\s+/g, " ")}`,
    input.instructions ? `- Instructions: ${input.instructions.replace(/\s+/g, " ")}` : null,
    `- Generated by VerityAI (${input.pipelineVersion}, model ${input.model})${
      input.completedAt ? ` on ${input.completedAt.toISOString().slice(0, 10)}` : ""
    }`,
    `- Report version ${input.version}${input.version > 1 ? " (revised after fact-checking)" : ""}`,
  ].filter(Boolean);
  if (input.scorecard) {
    const s = input.scorecard;
    about.push(
      `- Automatic checks: claim support ${pct(s.claimSupportRate)}, citation accuracy ${pct(s.citationAccuracy)}, citation validity ${pct(s.citationValidity)}, source reliability ${pct(s.sourceReliability)}, coverage ${pct(s.coverage)}, task completion ${pct(s.taskCompletion)}, policy ${s.policyCompliant ? "compliant" : "violated"}. ${s.passed ? "Meets every target." : "Below target on at least one check: read critically."}`,
    );
  } else {
    about.push("- This report was not automatically checked.");
  }
  parts.push("## About this report", about.join("\n"));
  return `${parts.join("\n\n")}\n`;
}
